"""
r1_ecospat_prepare.py — R1 item KM-5, step 1: environmental background per range for
the ecospat niche-dynamics analysis (Broennimann et al. 2012; Guisan et al. 2014).

Background definition (target-group, per range)
  All crayfish records in the GeoTraits table - every species and every status
  (Native, Introduced, Alien, Type locality) - that pass the same quality filters as
  the occurrences (High accuracy, snapping <= 1 km), kept once per stream segment
  (subc_id), and lying within B km (great-circle) of at least one record of the
  focal species in that range. B = 100 km is primary; 50 and 200 km are sensitivity
  runs. The target group shares the recording effort of the occurrences (Phillips et
  al. 2009), and the buffer approximates the area accessible to each range.

  Environmental values for stream segments without any crayfish record are not in
  the GeoTraits table, so a background of all segments in the occupied basins is not
  available here. GeoTraits basin_id cannot be used to delimit basins either (see
  r1_basin_id_audit.py).

Variables: the species' cleaned variable set used by the classifiers. Background and
occurrence records with > 50 % missing values are dropped; remaining gaps are filled
with the median of the pooled background of both ranges (same values for both).

Outputs (results/revision/ecospat_input/<species>/<B>km/):
  bg_native.csv, bg_nonnative.csv, occ_native.csv, occ_nonnative.csv, variables.txt
  plus results/revision/tables/r1_ecospat_background_summary.csv
  The ecospat_input files are record-level environmental values and are not tracked in
  git (World of Crayfish data policy); they are regenerated by this script.

Run (from conservation/):  ../.venv/bin/python src/r1_ecospat_prepare.py
"""
from __future__ import annotations

import argparse

import numpy as np
import pandas as pd
from sklearn.neighbors import BallTree

from data_loader import load_config, load_geotraits, COL_ACCURACY, COL_DISTANCE, COL_SEGMENT, COL_SPECIES, COL_STATUS
from r1_common import INPUT, CONFIG, LAT, LON, OUT, SPECIES, TABLES, build_species_frame, ensure_dirs, env_columns, load_filtered

BUFFERS_KM = [50, 100, 200]
EARTH_KM = 6371.0


def target_group_records(raw: pd.DataFrame, config: dict) -> pd.DataFrame:
    crit = config["selection_criteria"]
    d = raw[(raw[COL_ACCURACY] == crit.get("accuracy_filter", "High"))
            & (raw[COL_DISTANCE] <= crit.get("max_snapping_distance", 1000))].copy()
    d = d.dropna(subset=[LAT, LON])
    return d.drop_duplicates(subset=[COL_SEGMENT], keep="first").reset_index(drop=True)


def within_km(points_lat, points_lon, ref_lat, ref_lon, km):
    tree = BallTree(np.radians(np.c_[ref_lat, ref_lon]), metric="haversine")
    dist, _ = tree.query(np.radians(np.c_[points_lat, points_lon]), k=1)
    return dist[:, 0] * EARTH_KM <= km


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache", default=None)
    args = ap.parse_args()
    ensure_dirs()

    config = load_config(CONFIG)
    raw = load_geotraits(INPUT)
    tg = target_group_records(raw, config)
    dff = load_filtered(args.cache)
    assert dff["WoCID"].is_unique, "WoCID must identify records uniquely"
    env = env_columns(dff)
    print(f"Target-group pool: {len(tg):,} records (one per stream segment)")

    rows = []
    for sp in SPECIES:
        combined, clean = build_species_frame(dff, sp, env)
        # raw (non-imputed) occurrence values, re-imputed below with background medians
        occ_raw = dff.set_index("WoCID").loc[combined["WoCID"], clean + [LAT, LON]].reset_index()
        occ_raw["range_label"] = combined["range_label"].to_numpy()
        for B in BUFFERS_KM:
            bgs = {}
            for rng in ("native", "non-native"):
                ref = occ_raw[occ_raw.range_label == rng]
                keep = within_km(tg[LAT].to_numpy(), tg[LON].to_numpy(), ref[LAT].to_numpy(), ref[LON].to_numpy(), B)
                bgs[rng] = tg.loc[keep, clean + [LAT, LON, COL_SPECIES, COL_STATUS]].copy()
            pooled = pd.concat(bgs.values())
            pooled = pooled[pooled[clean].isna().mean(axis=1) <= 0.5]
            med = pooled[clean].median()
            outdir = OUT / "ecospat_input" / sp.replace(" ", "_").lower() / f"{B}km"
            outdir.mkdir(parents=True, exist_ok=True)
            for rng, bg in bgs.items():
                n0 = len(bg)
                bg = bg[bg[clean].isna().mean(axis=1) <= 0.5].copy()
                bg[clean] = bg[clean].fillna(med)
                tag = "native" if rng == "native" else "nonnative"
                bg[clean].to_csv(outdir / f"bg_{tag}.csv", index=False)
                occ = occ_raw[occ_raw.range_label == rng].copy()
                occ = occ[occ[clean].isna().mean(axis=1) <= 0.5]
                occ[clean] = occ[clean].fillna(med)
                occ[clean].to_csv(outdir / f"occ_{tag}.csv", index=False)
                rows.append({
                    "species": sp, "buffer_km": B, "range": rng,
                    "n_occurrences": len(occ), "n_background": len(bg),
                    "n_background_dropped_missing": n0 - len(bg),
                    "background_n_species": bg[COL_SPECIES].nunique(),
                    "background_share_focal_species": float((bg[COL_SPECIES] == sp).mean()),
                    "background_status_mix": "; ".join(f"{k}={v}" for k, v in bg[COL_STATUS].value_counts().items()),
                    "n_variables": len(clean),
                })
            (outdir / "variables.txt").write_text("\n".join(clean) + "\n")
            print(f"  {sp} {B} km: native bg {rows[-2]['n_background']}, non-native bg {rows[-1]['n_background']}")

    pd.DataFrame(rows).to_csv(TABLES / "r1_ecospat_background_summary.csv", index=False)
    print(f"Saved {TABLES / 'r1_ecospat_background_summary.csv'}")


if __name__ == "__main__":
    main()
